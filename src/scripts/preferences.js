  const langBtn = document.getElementById("lang-dropdown-btn");
  const langMenu = document.getElementById("lang-dropdown-menu");
  const langLabel = langBtn ? langBtn.querySelector("span") : null;

  if (langBtn && langMenu) {
    // Toggle dropdown
    langBtn.addEventListener("click", (e) => {
      e.stopPropagation();
      const isExpanded = langBtn.getAttribute("aria-expanded") === "true";
      langBtn.setAttribute("aria-expanded", !isExpanded);
      if (isExpanded) {
        langMenu.setAttribute("hidden", "");
      } else {
        langMenu.removeAttribute("hidden");
      }
    });

    // Close when clicking outside
    document.addEventListener("click", (e) => {
      if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
        langBtn.setAttribute("aria-expanded", "false");
        langMenu.setAttribute("hidden", "");
      }
    });

    // Handle selection
    langMenu.querySelectorAll(".dropdown-item").forEach(item => {
      item.addEventListener("click", () => {
        const lang = item.getAttribute("data-value");
        localStorage.setItem("language", lang);
        updateLanguageUI(lang);
        document.dispatchEvent(new CustomEvent("langChanged", { detail: lang }));
        langBtn.setAttribute("aria-expanded", "false");
        langMenu.setAttribute("hidden", "");
      });
    });
  }

  const updateLanguageUI = (lang) => {
    const t = uiTranslations[lang] || uiTranslations["en"];
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (t[key]) {
        el.textContent = t[key];
      }
    });

    const chatInput = document.getElementById("chat-input");
    const btnSend = document.getElementById("btn-send");

    if (langLabel) {
      langLabel.textContent = t.label;
    }

    if (chatInput) {
      chatInput.placeholder = t.placeholder;
    }
    
    if (btnSend && btnSend.textContent.trim().match(/^[A-Za-z]+$/)) {
      btnSend.textContent = t.send;
    }
  };

  const initLanguage = () => {
    const savedLanguage = localStorage.getItem("language") || "en";
    updateLanguageUI(savedLanguage);
  };

  // Initialize both
  initTheme();
  initLanguage();


